export const RARITY_COLORS: Record<SBTIPersonality['rarity'], string> = {
  common: '#9CA3AF',
  rare: '#3B82F6',
  epic: '#A855F7',
  legendary: '#F59E0B',
  mythic: '#EF4444',
};

export function matchPersonality(answers: number[]): SBTIPersonality {
  // 取前15个答案映射到15维度（前15题，每题代表一个维度）
  // 每道题的答案（A=0, B=1, C=2）就是该维度的值
  const vector = answers.slice(0, 15).map(a => a ?? 1);

  let minDist = Infinity;
  let matched = SBTI_PERSONALITIES[0];

  for (const p of SBTI_PERSONALITIES) {
    let dist = 0;
    for (let i = 0; i < 15; i++) {
      dist += Math.abs(vector[i] - p.vector[i]);
    }
    if (dist < minDist) {
      minDist = dist;
      matched = p;
    }
  }

  return matched;
}
